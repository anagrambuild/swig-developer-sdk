import { Keypair, PublicKey, Transaction } from '@solana/web3.js';
import { describe, expect, test } from 'bun:test';
import fixture from '../../../test-fixtures/reserved-wallet.json';
import { signPreparedSwigTransaction } from '../client/swig-signing.js';
import { SwigClient } from '../server/typescript/index.js';
import { type DirectWalletAuthority } from '../types/wallet-actions.js';

const address = new PublicKey(new Uint8Array(32).fill(3)).toBase58();
const config = new PublicKey(new Uint8Array(32).fill(4)).toBase58();
const wallet = { swigConfigAddress: config, walletAddress: address };
const rootAuthority = {
  ed25519: { publicKey: address },
} satisfies DirectWalletAuthority;
const reservation = { wallet, network: 'NETWORK_DEVNET' };
const transaction = {
  transaction: 'prepared-transaction',
  transactionEncoding: 'TRANSACTION_ENCODING_BASE64',
  kind: 'PREPARED_TRANSACTION_KIND_CREATE_SWIG_WALLET',
  network: 'NETWORK_DEVNET',
  wallet,
};

function client(response: unknown, requests: Request[]): SwigClient {
  return new SwigClient({
    apiKey: 'test-key',
    network: 'devnet',
    baseUrl: 'https://example.test',
    fetch: Object.assign(
      async (input: RequestInfo | URL, init?: RequestInit) => {
        requests.push(new Request(input, init));
        return Response.json(response);
      },
      { preconnect() {} },
    ),
  });
}

describe('reserved wallets', () => {
  test('uses the same authority and options for lookup and creation', async () => {
    for (const addressOptions of [
      undefined,
      { accountIndex: 0 },
      { accountIndex: 0xffffffff },
      { salt: new Uint8Array(32) },
    ]) {
      const requests: Request[] = [];
      const swig = client(
        { data: { ...reservation, transactions: [transaction] } },
        requests,
      );
      const reserved = await swig.wallets.reserveAddress({
        rootAuthority,
        addressOptions,
      });
      const created = await swig.wallets.createReserved({
        rootAuthority,
        addressOptions,
        feePayer: address,
      });
      expect(created.wallet).toEqual(reserved.wallet);
      expect(created.creationTransaction?.signatureRequests).toEqual([]);
      expect(requests.map((request) => new URL(request.url).pathname)).toEqual([
        '/transaction/api/wallet/reserve',
        '/transaction/api/wallet/create-reserved',
      ]);
      const lookup = await requests[0]?.json();
      expect(lookup).toMatchObject({
        rootAuthority,
        network: 'NETWORK_DEVNET',
      });
      expect(await requests[1]?.json()).toEqual({
        ...lookup,
        feePayer: address,
      });
      expect(lookup.addressOptions).toEqual(
        addressOptions &&
          ('salt' in addressOptions
            ? { salt: 'AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=' }
            : addressOptions),
      );
    }
  });

  test('rejects invalid options before HTTP', async () => {
    const requests: Request[] = [];
    const swig = client(reservation, requests);
    for (const accountIndex of [-1, 0x100000000, 0.5, NaN]) {
      await expect(
        swig.wallets.reserveAddress({
          rootAuthority,
          addressOptions: { accountIndex },
        }),
      ).rejects.toThrow();
    }
    await expect(
      swig.wallets.reserveAddress({
        rootAuthority,
        addressOptions: { salt: new Uint8Array(31) },
      }),
    ).rejects.toThrow();
    await expect(
      swig.wallets.createReserved({ rootAuthority, feePayer: '' }),
    ).rejects.toThrow();
    expect(requests).toHaveLength(0);
  });

  test('rejects missing addresses, wrong networks and inconsistent creation batches', async () => {
    for (const response of [
      null,
      {},
      { ...reservation, wallet: {} },
      { ...reservation, network: 'NETWORK_MAINNET' },
    ]) {
      await expect(
        client(response, []).wallets.reserveAddress({ rootAuthority }),
      ).rejects.toThrow();
    }
    for (const transactions of [
      [],
      [transaction, transaction],
      [{ ...transaction, wallet: { ...wallet, walletAddress: config } }],
      [{ ...transaction, network: 'NETWORK_MAINNET' }],
      [{ ...transaction, kind: 'PREPARED_TRANSACTION_KIND_TRANSFER_SOL' }],
    ]) {
      await expect(
        client({ ...reservation, transactions }, []).wallets.createReserved({
          rootAuthority,
          feePayer: address,
        }),
      ).rejects.toThrow();
    }
  });
});

// Fixture generated by swig-transaction's canonical reservation builder (869f5eb).
test('reserved creation can be decoded and signed by only the fee payer', async () => {
  const payer = Keypair.fromSeed(
    Buffer.from(
      '9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60',
      'hex',
    ),
  );
  const swig = client(fixture, []);
  const created = await swig.wallets.createReserved({
    rootAuthority: { ed25519: { publicKey: payer.publicKey.toBase58() } },
    feePayer: payer.publicKey.toBase58(),
  });
  if (!created.creationTransaction) throw new Error('missing creation');
  const prepared = await signPreparedSwigTransaction(
    created.creationTransaction,
    {},
  );
  const transaction = Transaction.from(
    Buffer.from(prepared.transaction, 'base64'),
  );
  expect(transaction.compileMessage().header.numRequiredSignatures).toBe(1);
  expect(transaction.feePayer?.toBase58()).toBe(payer.publicKey.toBase58());
  expect(transaction.instructions[1]?.data.subarray(0, 2)).toEqual(
    Buffer.from([24, 0]),
  );
  const message = transaction.serializeMessage();
  transaction.partialSign(payer);
  expect(transaction.verifySignatures()).toBe(true);
  expect(transaction.serializeMessage()).toEqual(message);
  expect(transaction.serialize().length).toBeGreaterThan(0);
});
